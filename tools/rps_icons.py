"""Draws the game page's three icons (rock, paper, scissors) and writes main/rps_icons.c (LVGL 9 images, RGB565A8).

No dependency: each icon is a few flat shapes (circles, rectangles, thick segments), anti-aliased by 4x4
supersampling. Run it again after changing a shape:   python tools/rps_icons.py
"""
import math
import os

SIZE = 112      # px; ui.c places them for this size
SS = 4          # samples per pixel per axis


def hexc(v):
    return ((v >> 16) & 255, (v >> 8) & 255, v & 255)


def in_circle(x, y, cx, cy, r):
    return (x - cx) ** 2 + (y - cy) ** 2 <= r * r


def in_ring(x, y, cx, cy, r, w):
    d = math.hypot(x - cx, y - cy)
    return r - w / 2 <= d <= r + w / 2


def in_segment(x, y, ax, ay, bx, by, w):
    dx, dy = bx - ax, by - ay
    t = max(0.0, min(1.0, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(x - (ax + t * dx), y - (ay + t * dy)) <= w / 2


def in_poly(x, y, pts):
    inside = False
    for i in range(len(pts)):
        (x1, y1), (x2, y2) = pts[i], pts[i - 1]
        if (y1 > y) != (y2 > y) and x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
            inside = not inside
    return inside


# Each icon: a function (x, y) -> (r, g, b) or None, x and y in pixels (sample centres)
ROCK = [(16, 76), (12, 56), (26, 34), (50, 20), (78, 26), (98, 48), (100, 74), (84, 94), (46, 100), (24, 92)]
ROCK_TOP = [(26, 36), (50, 22), (77, 28), (68, 50), (38, 54)]          # the lit face
ROCK_SIDE = [(68, 50), (77, 28), (97, 49), (99, 73), (80, 70)]          # the half-lit face


def rock(x, y):
    if not in_poly(x, y, ROCK):
        return None
    if in_poly(x, y, ROCK_TOP):
        return hexc(0xC9D0D8)
    if in_poly(x, y, ROCK_SIDE):
        return hexc(0xA3ACB6)
    if in_circle(x, y, 40, 78, 3) or in_circle(x, y, 66, 84, 2.5):
        return hexc(0x5C6470)
    return hexc(0x7F8893)


def paper(x, y):
    x0, y0, x1, y1, fold = 24, 12, 88, 100, 18
    if not (x0 <= x <= x1 and y0 <= y <= y1):
        return None
    if x > x1 - fold and y < y0 + fold:                     # the folded top-right corner
        if (x - (x1 - fold)) > (y - y0):
            return None
        return hexc(0xC3C9D0)
    for ly, lx1 in [(44, 76), (58, 76), (72, 76), (86, 62)]:
        if abs(y - ly) <= 2 and 34 <= x <= lx1:
            return hexc(0x8B95A1)
    return hexc(0xF2F4F7)


def scissors(x, y):
    if in_ring(x, y, 34, 88, 12, 6) or in_ring(x, y, 78, 88, 12, 6):
        return hexc(0xFF6A3D)
    if in_circle(x, y, 56, 50, 4):
        return hexc(0x5C6470)
    if in_segment(x, y, 42, 78, 88, 10, 8) or in_segment(x, y, 70, 78, 24, 10, 8):
        return hexc(0xD3D8DE)
    return None


def render(fn):
    rgb, alpha = [], []
    for py in range(SIZE):
        for px in range(SIZE):
            n = 0
            acc = [0, 0, 0]
            for sy in range(SS):
                for sx in range(SS):
                    c = fn(px + (sx + 0.5) / SS, py + (sy + 0.5) / SS)
                    if c:
                        n += 1
                        for i in range(3):
                            acc[i] += c[i]
            a = n * 255 // (SS * SS)
            if n:
                r, g, b = (v // n for v in acc)
            else:
                r = g = b = 0
            rgb.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
            alpha.append(a)
    data = bytearray()
    for v in rgb:
        data += bytes((v & 255, v >> 8))   # RGB565 little-endian, then the alpha plane (LVGL's RGB565A8)
    data += bytes(alpha)
    return data


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    body = "\n".join(lines)
    return f"""static const uint8_t {name}_data[{len(data)}] = {{
{body}
}};
const lv_image_dsc_t {name} = {{
    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .w = {SIZE}, .h = {SIZE},
                .stride = {SIZE * 2} }},
    .data_size = sizeof({name}_data),
    .data = {name}_data,
}};
"""


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = [
        "// Generated by tools/rps_icons.py: do not edit (change the shapes there and run it again).",
        "// The game page's icons, %d x %d, RGB565A8." % (SIZE, SIZE),
        '#include "rps_icons.h"',
        "",
    ]
    for name, fn in [("rps_icon_rock", rock), ("rps_icon_paper", paper), ("rps_icon_scissors", scissors)]:
        out.append(c_array(name, render(fn)))
    with open(os.path.join(root, "main", "rps_icons.c"), "w", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
